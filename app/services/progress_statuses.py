assert _STATUS_COUNT == 180, f"Expected 180 predefined statuses, got {_STATUS_COUNT}"
assert all(len(statuses) == 10 for _, _, statuses in _CATEGORIES)


def select_progress_statuses(user_text: Any) -> list[str]:
    """Return ten relevant static statuses; never calls a model or external API."""
    text = str(user_text or "").casefold().replace("ё", "е")[:10000]
    scored: list[tuple[int, int, tuple[str, ...]]] = []
    general = next(statuses for name, _, statuses in _CATEGORIES if name == "general")

    for order, (name, keywords, statuses) in enumerate(_CATEGORIES):
        if name == "general":
            continue
        score = sum(1 for keyword in keywords if keyword.replace("ё", "е") in text)
        if score:
            scored.append((score, -order, statuses))

    if not scored:
        return list(general)

    scored.sort(key=lambda item: (item[0], item[1]), reverse=True)
    primary_score, _, primary = scored[0]
    if len(scored) > 1:
        secondary_score, _, secondary = scored[1]
        if secondary_score >= max(2, primary_score * 0.6):
            return list(primary[:7] + secondary[:3])
    return list(primary)

